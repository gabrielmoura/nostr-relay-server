-- RelaySync v2 transactional outbox.
-- The outbox is populated in the same transaction as event visibility changes.
-- relay_sync_journal is intentionally populated by a future projector, which
-- must order rows by PostgreSQL commit metadata before assigning its cursor.

CREATE TABLE IF NOT EXISTS public.relay_sync_outbox (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    txid BIGINT NOT NULL DEFAULT txid_current(),
    operation TEXT NOT NULL CHECK (operation IN ('UPSERT', 'DELETE')),
    event_id TEXT NOT NULL,
    pubkey TEXT,
    created_at INTEGER,
    kind INTEGER,
    tags JSONB,
    content TEXT,
    sig TEXT,
    scope_name TEXT NOT NULL DEFAULT 'public',
    scope_version INTEGER NOT NULL DEFAULT 1,
    scope_hash BYTEA NOT NULL DEFAULT decode(repeat('00', 32), 'hex'),
    observed_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    published_at TIMESTAMPTZ,
    journal_epoch BIGINT,
    journal_sequence BIGINT,
    CONSTRAINT relay_sync_outbox_scope_hash_length CHECK (octet_length(scope_hash) = 32)
);

CREATE INDEX IF NOT EXISTS relay_sync_outbox_pending_idx
    ON public.relay_sync_outbox (observed_at, id)
    WHERE published_at IS NULL;

CREATE TABLE IF NOT EXISTS public.relay_sync_journal (
    epoch BIGINT NOT NULL,
    sequence BIGINT NOT NULL,
    outbox_id BIGINT NOT NULL UNIQUE REFERENCES public.relay_sync_outbox(id),
    txid BIGINT NOT NULL,
    committed_at TIMESTAMPTZ NOT NULL,
    operation TEXT NOT NULL CHECK (operation IN ('UPSERT', 'DELETE')),
    event_id TEXT NOT NULL,
    pubkey TEXT,
    created_at INTEGER,
    kind INTEGER,
    tags JSONB,
    content TEXT,
    sig TEXT,
    scope_name TEXT NOT NULL,
    scope_version INTEGER NOT NULL,
    scope_hash BYTEA NOT NULL,
    PRIMARY KEY (epoch, sequence),
    CONSTRAINT relay_sync_journal_scope_hash_length CHECK (octet_length(scope_hash) = 32)
);

CREATE INDEX IF NOT EXISTS relay_sync_journal_scope_cursor_idx
    ON public.relay_sync_journal (scope_name, scope_version, epoch, sequence);

CREATE OR REPLACE FUNCTION public.relay_sync_enqueue_outbox()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
    source_row public.event%ROWTYPE;
    change_operation TEXT;
BEGIN
    IF TG_OP = 'DELETE' THEN
        source_row := OLD;
        change_operation := 'DELETE';
    ELSIF TG_OP = 'UPDATE' THEN
        -- Fake deletion changes visibility without removing the payload.
        IF NEW.deleted_by IS NOT DISTINCT FROM OLD.deleted_by THEN
            RETURN NEW;
        END IF;
        source_row := NEW;
        change_operation := CASE WHEN NEW.deleted_by IS NULL THEN 'UPSERT' ELSE 'DELETE' END;
    ELSE
        source_row := NEW;
        change_operation := 'UPSERT';
    END IF;

    INSERT INTO public.relay_sync_outbox (
        operation, event_id, pubkey, created_at, kind, tags, content, sig
    ) VALUES (
        change_operation, source_row.id, source_row.pubkey, source_row.created_at,
        source_row.kind, source_row.tags, source_row.content, source_row.sig
    );
    IF TG_OP = 'DELETE' THEN
        RETURN OLD;
    END IF;
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS relay_sync_event_outbox_trigger ON public.event;
CREATE TRIGGER relay_sync_event_outbox_trigger
AFTER INSERT OR DELETE OR UPDATE OF deleted_by ON public.event
FOR EACH ROW EXECUTE FUNCTION public.relay_sync_enqueue_outbox();
