-- ============================================================
-- PostgreSQL 18 optimized schema — v2 (refatorado)
-- ============================================================
-- Decisões tomadas nesta revisão:
--   1) Prefixo hex (ex.: id LIKE 'abc%') É usado pelo relay -> mantido
--      o índice UNIQUE text_pattern_ops em event.id.
--   2) Adicionado índice GIN em tagvalues (estava órfão: coluna gerada
--      sem índice de suporte).
--   3) Limpeza de eventos expirados é feita por um CRON externo ->
--      não foi adicionada coluna/índice de expires_at aqui.
--   4) Particionamento por data é PLANO FUTURO: a estratégia definida
--      é mover eventos antigos (ex.: > 5 anos) para uma tabela de
--      arquivamento separada, não particionamento nativo. Por isso
--      o índice parcial com epoch hardcoded (idx_event_recent) foi
--      removido — ele é um paliativo que a estratégia de arquivamento
--      torna desnecessário e que exigiria manutenção manual constante.
--   5) Não há limite de quantidade de tags no banco (chegam a existir
--      eventos com ~2000 tags). Por isso os índices sobre `tags` e
--      `tagvalues` usam GIN (não sofre do limite de ~2712 bytes por
--      tupla de índice btree que afeta índices "covering"). A
--      restrição de tamanho de payload, se necessária, fica na
--      camada de aplicação.
-- ============================================================

CREATE SCHEMA IF NOT EXISTS public;

