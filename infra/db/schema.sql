CREATE TABLE IF NOT EXISTS public.event (
                                            id TEXT PRIMARY KEY,
                                            pubkey TEXT NOT NULL,
                                            created_at INTEGER NOT NULL,
                                            kind INTEGER NOT NULL,
                                            tags JSONB NOT NULL,
                                            content TEXT NOT NULL,
