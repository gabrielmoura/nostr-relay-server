-- ============================================================
-- Trigger idempotente para expiration
-- ============================================================

DO $$
    BEGIN
        IF NOT EXISTS (
            SELECT 1
            FROM pg_trigger
            WHERE tgname = 'trg_event_expiration'
        ) THEN
            CREATE TRIGGER trg_event_expiration
                BEFORE INSERT ON public.event
                FOR EACH ROW
            EXECUTE FUNCTION public.nostr_expiration_submission();
        END IF;
    END $$;

